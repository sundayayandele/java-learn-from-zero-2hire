#!/usr/bin/env python3
"""Generate every README.md under phases/ from the authored sources.

Authored (edit these):
    curriculum.json                          phases, modules, topics, weeks
    phases/<phase>/phase.md                  phase introduction
    phases/<phase>/<module>/module.md        module introduction and projects
    phases/<phase>/<module>/<topic>/lesson.md   reading content
    phases/<phase>/<module>/<topic>/cbt.json    topic quiz
    phases/<phase>/deploy/guide.md, getting-hired/guide.md
    lms/videos.json                          videos per topic

Generated (do not edit): README.md next to each of the files above, and CURRICULUM.md.

    python scripts/build.py           # write files
    python scripts/build.py --check   # exit 1 if any generated file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANNER = "<!-- GENERATED by scripts/build.py from {src}. Edit the source, then run `python scripts/build.py`. -->\n\n"
LETTERS = "ABCDEFGH"


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def fmt_minutes(m: float) -> str:
    return f"{m / 60:.1f} h" if m >= 90 else f"{round(m)} min"


def watch_section(vids: list[dict], heading: str = "## Watch") -> str:
    if not vids:
        return ""
    core = [v for v in vids if not v.get("optional")]
    extra = [v for v in vids if v.get("optional")]
    lines = [heading, "", "All videos are in English with English captions and were checked on "
             f"{VIDEOS.get('checked') or 'the last build'}. Moodle learners see them embedded.", ""]

    def item(v):
        return (f"- [{v['title']}](https://www.youtube.com/watch?v={v['id']}) · {v['channel']} · "
                f"{fmt_minutes(v['minutes'])}. {v['why']}")

    lines += [item(v) for v in core]
    if extra:
        lines += ["", "**Want more depth? (longer, optional)**", ""] + [item(v) for v in extra]
    return "\n".join(lines) + "\n"


def cbt_section(cbt: dict) -> str:
    qs = cbt["questions"]
    lines = ["## Check your understanding", "",
             f"{len(qs)} scenario questions. Answer each one before opening the explanation. "
             "On Moodle this is the graded topic quiz (pass mark 70%, unlimited attempts).", ""]
    for i, q in enumerate(qs, 1):
        kind = " *(choose all that apply)*" if q["type"] == "multi" else ""
        lines.append(f"**Q{i}.** {q['scenario']}")
        lines.append("")
        lines.append(f"{q['question']}{kind}")
        lines.append("")
        for j, opt in enumerate(q["options"]):
            lines.append(f"- {LETTERS[j]}. {opt}")
        ans = q["answer"] if isinstance(q["answer"], list) else [q["answer"]]
        letters = ", ".join(LETTERS[a] for a in ans)
        lines += ["", "<details><summary>Answer</summary>", "",
                  f"**{letters}.** {q['explanation']}", "", "</details>", ""]
    return "\n".join(lines)


def nav(items: list[str]) -> str:
    return " · ".join(i for i in items if i) + "\n"


def rel(from_dir: Path, to: Path) -> str:
    import os
    return os.path.relpath(to, from_dir).replace(os.sep, "/")


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    cur = load(ROOT / "curriculum.json")
    for phase in cur["phases"]:
        pdir = ROOT / "phases" / phase["slug"]
        if phase["status"] != "built":
            out[pdir / "README.md"] = planned_phase(phase, pdir)
            continue
        flat = [(m, t) for m in phase["modules"] for t in m["topics"]]
        for idx, (mod, t) in enumerate(flat):
            mdir = pdir / mod["slug"]
            tdir = mdir / t["slug"]
            prev_link = next_link = ""
            if idx > 0:
                pm, pt = flat[idx - 1]
                prev_link = f"← [{pt['id']} {short(pt['title'])}]({rel(tdir, pdir / pm['slug'] / pt['slug'] / 'README.md')})"
            if idx + 1 < len(flat):
                nm, nt = flat[idx + 1]
                next_link = f"[{nt['id']} {short(nt['title'])}]({rel(tdir, pdir / nm['slug'] / nt['slug'] / 'README.md')}) →"
            bar = nav([prev_link, f"[Module {mod['number']}](../README.md)", f"[Phase {phase['number']}](../../README.md)", next_link])
            lesson = (tdir / "lesson.md").read_text(encoding="utf-8").strip()
            cbt = load(tdir / "cbt.json")
            body = [BANNER.format(src=f"{t['slug']}/lesson.md, cbt.json and lms/videos.json"),
                    f"# {t['id']} {t['title']}", "", bar,
                    f"> **Week {t['week']}** · Module {mod['number']}: {mod['title']} · "
                    f"Website topic covered: *{t['covers']}*", "",
                    lesson, "", watch_section(VIDEOS["topics"].get(t["id"], [])), cbt_section(cbt), "---", "", bar]
            out[tdir / "README.md"] = "\n".join(body)
        for mod in phase["modules"]:
            mdir = pdir / mod["slug"]
            intro = (mdir / "module.md").read_text(encoding="utf-8").strip()
            rows = ["| Topic | Week | Covers (website wording) |", "| --- | --- | --- |"]
            rows += [f"| [{t['id']} {t['title']}]({t['slug']}/README.md) | {t['week']} | {t['covers']} |" for t in mod["topics"]]
            out[mdir / "README.md"] = "\n".join([
                BANNER.format(src=f"{mod['slug']}/module.md and curriculum.json"),
                f"# Module {mod['number']}: {mod['title']} (weeks {mod['weeks']})", "",
                f"← [Phase {phase['number']}: {phase['title']}](../README.md) · [Home](../../../README.md)", "",
                "## Topics", "", *rows, "", intro, ""])
        intro = (pdir / "phase.md").read_text(encoding="utf-8").strip()
        out[pdir / "README.md"] = "\n".join([
            BANNER.format(src=f"phases/{phase['slug']}/phase.md and curriculum.json"),
            f"# Phase {phase['number']}: {phase['title']} (weeks {phase['weeks']})", "",
            "← [Home](../../README.md) · [Full curriculum](../../CURRICULUM.md)", "",
            intro, ""])
    for folder, video_key in GUIDE_PAGES:
        guide = (ROOT / folder / "guide.md").read_text(encoding="utf-8").strip()
        out[ROOT / folder / "README.md"] = "\n".join([
            BANNER.format(src=f"{folder}/guide.md and lms/videos.json"), guide, "",
            watch_section(VIDEOS["topics"].get(video_key, [])), ""])
    out[ROOT / "CURRICULUM.md"] = curriculum_md(cur)
    return out


def short(title: str) -> str:
    return title.split(":")[0]


def planned_phase(phase: dict, pdir: Path) -> str:
    lines = [BANNER.format(src="curriculum.json"),
             f"# Phase {phase['number']}: {phase['title']} (weeks {phase['weeks']})", "",
             "← [Home](../../README.md) · [Full curriculum](../../CURRICULUM.md)", "",
             f"> **Status: planned.** This phase will be built after the Phase 1 pilot is reviewed. "
             "The topic list below is final and matches the ITLearning programme page.", "",
             phase["summary"], ""]
    for mod in phase["modules"]:
        lines += [f"## Module {mod['number']}: {mod['title']} (weeks {mod['weeks']})", ""]
        lines += [f"- {t['id']} {t['title']}" for t in mod["topics"]]
        lines += ["", "Projects: " + "; ".join(mod["projects"]) + ".", ""]
    return "\n".join(lines)


def curriculum_md(cur: dict) -> str:
    lines = [BANNER.format(src="curriculum.json"), f"# {cur['title']}: full curriculum", "",
             f"Every phase, module and topic from the [ITLearning Java Backend Engineer programme]({cur['source']}) "
             f"(checked {cur['source_checked']}), with this repository's additions marked.", "",
             "## Stack", "", "| Area | Choice |", "| --- | --- |"]
    lines += [f"| {k.replace('_', ' ').title()} | {v} |" for k, v in cur["stack"].items()]
    lines.append("")
    total_topics = 0
    for phase in cur["phases"]:
        status = "built" if phase["status"] == "built" else "planned"
        lines += [f"## Phase {phase['number']}: {phase['title']} (weeks {phase['weeks']}) · {status}", "",
                  phase["summary"], ""]
        for mod in phase["modules"]:
            link = f"[Module {mod['number']}: {mod['title']}](phases/{phase['slug']}/{mod['slug']}/README.md)" \
                if status == "built" else f"Module {mod['number']}: {mod['title']}"
            lines += [f"### {link} (weeks {mod['weeks']})", ""]
            for t in mod["topics"]:
                total_topics += 1
                if status == "built":
                    lines.append(f"- [{t['id']} {t['title']}](phases/{phase['slug']}/{mod['slug']}/{t['slug']}/README.md)")
                else:
                    lines.append(f"- {t['id']} {t['title']}")
            lines += ["", "Projects: " + "; ".join(mod["projects"]) + ".", ""]
    lines += [f"_{total_topics} topics in total._", ""]
    return "\n".join(lines)


VIDEOS = load(ROOT / "lms" / "videos.json")

# Authored guide.md pages that get a generated README with a Watch section.
GUIDE_PAGES = [
    ("phases/01-foundations/deploy", "deploy"),
    ("phases/01-foundations/cicd", "cicd"),
    ("phases/01-foundations/getting-hired", "getting-hired"),
]


def main(argv: list[str]) -> int:
    files = build()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    print(f"build: {len(files)} files, {len(stale)} written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
