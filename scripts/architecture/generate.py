#!/usr/bin/env python3
"""Generate architecture diagrams, ADRs and the design section of every capstone README.

    python scripts/architecture/generate.py            # write .mmd, .drawio, README.md, ADRs; inject capstone sections
    python scripts/architecture/generate.py --render   # also render .svg and .png with mermaid-cli in Docker
    python scripts/architecture/generate.py --check    # exit 1 if any text output is stale (used by check_repo.py)

Source of truth: scripts/architecture/capstones.py (models) and builders.py (shared diagram shapes).
For each capstone, outputs go to phases/01-foundations/capstones/<slug>/architecture/:
    <kind>.mmd  Mermaid source   <kind>.drawio  diagrams.net source   <kind>.svg / <kind>.png  rendered images
    README.md   all diagrams with explanations and code    adr/NNNN-*.md  architecture decision records
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from capstones import ALL  # noqa: E402
from model import Architecture, Decision, to_drawio, to_mermaid  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
CAPSTONES = ROOT / "phases" / "01-foundations" / "capstones"
MERMAID_IMAGE = "ghcr.io/mermaid-js/mermaid-cli/mermaid-cli:11.4.2"
START, END = "<!-- ARCHITECTURE:START (generated by scripts/architecture/generate.py) -->", "<!-- ARCHITECTURE:END -->"
ORDER = ["solution", "logical", "technical", "infra", "cloud"]
NAMES = {"solution": "Solution architecture", "logical": "Logical architecture", "technical": "Technical architecture",
         "infra": "Infrastructure architecture", "cloud": "Cloud architecture"}
QUESTIONS = {
    "solution": "Who uses the system, what does it integrate with, and where is its boundary?",
    "logical": "What are the capabilities and data, independent of technology?",
    "technical": "How is the code organised inside the service?",
    "infra": "Where does it run on a VPS, and how does code get there?",
    "cloud": "How does it map to managed cloud services on AWS, Azure and GCP?",
}
BANNER = "<!-- GENERATED by scripts/architecture/generate.py. Edit scripts/architecture/capstones.py instead. -->\n\n"


def slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60]


def adr_md(n: int, d: Decision, arch: Architecture) -> str:
    return (BANNER + f"# ADR {n:04d}: {d.title}\n\n"
            f"← [Architecture](../README.md) · [Capstone brief](../../README.md)\n\n"
            f"- **Status:** {d.status}\n- **Capstone:** {arch.title}\n\n"
            f"## Context\n\n{d.context}\n\n## Decision\n\n{d.decision}\n\n"
            f"## Consequences\n\n{d.consequences}\n\n## Alternatives considered\n\n{d.alternatives}\n")


def architecture_readme(arch: Architecture) -> str:
    by_kind = {d.kind: d for d in arch.diagrams}
    out = [BANNER + f"# {arch.title}: architecture and system design", "",
           "← [Capstone brief](../README.md) · [All capstones](../../README.md)", "",
           arch.summary, "",
           "Five views of the same system, from the business context down to the cloud. Read them in order: each answers "
           "a different question that system-design interviews ask. Every diagram is provided as **Mermaid** (renders on "
           "GitHub), **draw.io / diagrams.net** XML (open and edit at [app.diagrams.net](https://app.diagrams.net)), "
           "**SVG** and **PNG**.", "",
           "| # | View | Question it answers | Files |", "| --- | --- | --- | --- |"]
    for i, k in enumerate(ORDER, 1):
        out.append(f"| {i} | [{NAMES[k]}](#{i}-{slugify(NAMES[k])}) | {QUESTIONS[k]} | "
                   f"[svg]({k}.svg) · [png]({k}.png) · [mermaid]({k}.mmd) · [draw.io]({k}.drawio) |")
    out += ["", "**Legend:** blue = people/clients · green = services · white = components · yellow cylinders = "
            "databases · grey cylinders = caches/storage · red dashed = external systems · purple = infrastructure · "
            "orange = scheduled/batch jobs.", ""]
    for i, k in enumerate(ORDER, 1):
        d = by_kind[k]
        out += [f"## {i}. {NAMES[k]}", "", f"![{d.title}]({k}.svg)", "", d.explanation, "",
                "<details><summary>Mermaid source</summary>", "", "```mermaid", to_mermaid(d).rstrip(), "```", "", "</details>", ""]
    out += ["## Architecture decisions", "", "| ADR | Decision |", "| --- | --- |"]
    for n, dec in enumerate(arch.decisions, 1):
        out.append(f"| [{n:04d}](adr/{n:04d}-{slugify(dec.title)}.md) | {dec.title} |")
    out += ["", "## Use these in your own capstone", "",
            "Copy this folder into your repository, then change the diagrams to match what you actually built. In "
            "interviews, walk through the solution view first, then the logical view, then answer deep-dive questions "
            "with the technical, infrastructure and cloud views. Write a new ADR whenever you make a decision a future "
            "teammate would ask \"why?\" about.", ""]
    return "\n".join(out)


def capstone_section(arch: Architecture) -> str:
    by_kind = {d.kind: d for d in arch.diagrams}
    out = [START, "", "## Architecture and system design (read this first)", "",
           "Before you write code, study how this system is designed. These five views are the target architecture "
           "for a production-grade build; reproduce and adapt them in your own repository, and keep them current as you "
           "build. Full explanations, Mermaid, draw.io, SVG and PNG sources and the architecture decision records are in "
           "[architecture/](architecture/README.md).", ""]
    for i, k in enumerate(ORDER, 1):
        d = by_kind[k]
        first = d.explanation.split("\n\n")[0].replace("](../../../", "](../../")   # one level shallower than architecture/
        out += [f"### {i}. {NAMES[k]}", "", f"![{d.title}](architecture/{k}.svg)", "", first, "",
                f"Sources: [Mermaid](architecture/{k}.mmd) · [draw.io](architecture/{k}.drawio) · "
                f"[SVG](architecture/{k}.svg) · [PNG](architecture/{k}.png)", ""]
    out += ["### Key design decisions", ""]
    for n, dec in enumerate(arch.decisions, 1):
        out.append(f"{n}. [{dec.title}](architecture/adr/{n:04d}-{slugify(dec.title)}.md)")
    out += ["", END]
    return "\n".join(out)


def outputs(arch: Architecture) -> dict[Path, str]:
    base = CAPSTONES / arch.slug / "architecture"
    files: dict[Path, str] = {}
    for d in arch.diagrams:
        problems = d.validate()
        if problems:
            raise SystemExit(f"{arch.slug}: " + "; ".join(problems))
        files[base / f"{d.kind}.mmd"] = to_mermaid(d)
        files[base / f"{d.kind}.drawio"] = to_drawio(d, f"{arch.slug}-{d.kind}")
    files[base / "README.md"] = architecture_readme(arch)
    for n, dec in enumerate(arch.decisions, 1):
        files[base / "adr" / f"{n:04d}-{slugify(dec.title)}.md"] = adr_md(n, dec, arch)
    brief = CAPSTONES / arch.slug / "README.md"
    text = brief.read_text(encoding="utf-8")
    section = capstone_section(arch)
    if START in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: section, text, flags=re.S)
    else:
        lines = text.split("\n")
        nav = next(i for i, line in enumerate(lines) if line.startswith("←"))
        lines[nav + 1:nav + 1] = ["", section]
        text = "\n".join(lines)
    files[brief] = text
    return files


def render(paths: list[Path]) -> None:
    rel = [str(p.relative_to(ROOT)) for p in paths]
    script = "; ".join(f'$M -q -i "{r}" -o "{r[:-4]}.svg" -b white && $M -q -i "{r}" -o "{r[:-4]}.png" -b white -s 2'
                       for r in rel)
    subprocess.run(["docker", "run", "--rm", "-v", f"{ROOT}:/data", "-w", "/data", "--entrypoint", "sh",
                    MERMAID_IMAGE, "-c", "M=\"/home/mermaidcli/node_modules/.bin/mmdc -p /puppeteer-config.json\"; " + script], check=True)


def main(argv: list[str]) -> int:
    files: dict[Path, str] = {}
    for make in ALL:
        files.update(outputs(make()))
    stale = [p for p, t in files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if "--check" in argv:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python scripts/architecture/generate.py --render)", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    mmd = sorted(p for p in files if p.suffix == ".mmd")
    if "--render" in argv:
        render(mmd)
    print(f"architecture: {len(files)} files ({len(stale)} written), {len(mmd)} diagrams"
          + (" rendered to SVG and PNG" if "--render" in argv else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
