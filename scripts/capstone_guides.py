def guide(slug: str) -> str:
    title, repo, package, data, steps = CAPSTONES[slug]
    parts = [f"# Step-by-step build guide: {title}", "", BANNER, "",
             f"← [Capstone brief](README.md) · [Starter](starter/README.md) · [All capstones](../README.md)", "",
             "Work through the steps in order. Each step ends with a **Done when** check: don't move on until it passes. "
             "Commit after every step with a clear message, so your history tells the story of the build.", "",
             SETUP.format(slug=slug, repo=repo, title=title, package=package)]
    parts.append(DATA.format(commands="\n".join(data)) if data else NO_DATA)
    n = 4
    for step_title, items, done in steps:
        body = "\n".join(f"{i}. {item}" for i, item in enumerate(items, 1))
        parts.append(f"## Step {n}: {step_title}\n\n{body}\n\nDone when: {done}\n")
        n += 1
    parts.append(FINISH.format(n=n, n1=n + 1, n2=n + 2, n3=n + 3))
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str]) -> int:
    stale = []
    for slug in CAPSTONES:
        path = CAPSTONES_DIR / slug / "GUIDE.md"
        text = guide(slug)
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        if "--check" in argv:
            stale.append(path)
        else:
            path.write_text(text, encoding="utf-8")
    for p in stale:
        print(f"stale: {p.relative_to(ROOT)} (run python scripts/capstone_guides.py)", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
